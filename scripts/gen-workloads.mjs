/**
 * Finds every project in workloads/ and writes the two registry files the app
 * imports, so adding a project means adding a folder and nothing else. Runs
 * from next.config.ts, vitest.config.ts and the CLI. Folders starting with _
 * are skipped, which is how the template stays out of the list.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function generateRegistry(root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')) {
  const dir = path.join(root, 'workloads');
  const ids = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('_') && !e.name.startsWith('.'))
    .map((e) => e.name)
    .filter((id) => fs.existsSync(path.join(dir, id, 'meta.ts')) && fs.existsSync(path.join(dir, id, 'index.ts')))
    .sort();

  const banner = '// Generated by scripts/gen-workloads.mjs. Do not edit.\n';
  const name = (i) => `w${i}`;
  const metas = `${banner}import type { WorkloadMeta } from './types';\n${ids.map((id, i) => `import { meta as ${name(i)} } from '../../../workloads/${id}/meta';`).join('\n')}\n\nexport const REGISTERED_META: WorkloadMeta[] = [${ids.map((_, i) => name(i)).join(', ')}];\n`;
  const plugins = `${banner}import type { WorkloadPlugin } from './types';\n${ids.map((id, i) => `import { plugin as ${name(i)} } from '../../../workloads/${id}';`).join('\n')}\n\nexport const REGISTERED_PLUGINS: Record<string, WorkloadPlugin> = { ${ids.map((id, i) => `${JSON.stringify(id)}: ${name(i)}`).join(', ')} };\n`;

  const write = (file, text) => {
    const full = path.join(root, 'src', 'core', 'workload', file);
    if (!fs.existsSync(full) || fs.readFileSync(full, 'utf8') !== text) fs.writeFileSync(full, text);
  };
  write('registry-meta.generated.ts', metas);
  write('registry.generated.ts', plugins);
  return ids;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  console.log(`Workloads: ${generateRegistry().join(', ')}`);
}
